#!/usr/bin/env python3
"""Generates `Rules.lean`, the `notation ... in c` rules of the X64 syntax:
`python3 Kraken/X64/Parser/gen_rules.py > Kraken/X64/Parser/Rules.lean`.

The rules for one register, one operand form or one mnemonic stem are in one group, and the
columns of each group are aligned."""
import re
import sys

W = [(8, 'b'), (16, 'w'), (32, 'l'), (64, 'q')]
AVX = [(128, 'xmm'), (256, 'ymm'), (512, 'zmm')]
REG64 = ['rax', 'rbx', 'rcx', 'rdx', 'rsi', 'rdi', 'rsp', 'rbp'] + [f'r{i}' for i in range(8, 16)]
LEGACY = {'rax': 'a', 'rbx': 'b', 'rcx': 'c', 'rdx': 'd'}
IDX = {'rsi': 'si', 'rdi': 'di', 'rsp': 'sp', 'rbp': 'bp'}


def reg_name(r, n):
    if r in LEGACY:
        x = LEGACY[r]
        return {64: f'r{x}x', 32: f'e{x}x', 16: f'{x}x', 8: f'{x}l'}[n]
    if r in IDX:
        x = IDX[r]
        return {64: f'r{x}', 32: f'e{x}', 16: x, 8: f'{x}l'}[n]
    return {64: r, 32: r + 'd', 16: r + 'w', 8: r + 'b'}[n]


# Condition codes: spelling -> constructor. The constructor's own spelling is the one printed.
CC = [('o', 'o'), ('no', 'no'), ('z', 'z'), ('e', 'z'), ('nz', 'nz'), ('ne', 'nz'),
      ('b', 'c'), ('c', 'c'), ('nae', 'c'), ('ae', 'nc'), ('nc', 'nc'), ('nb', 'nc'),
      ('a', 'a'), ('nbe', 'a'), ('be', 'be'), ('na', 'be'), ('s', 's'), ('ns', 'ns'),
      ('p', 'p'), ('pe', 'p'), ('np', 'np'), ('po', 'np'), ('l', 'l'), ('nge', 'l'),
      ('ge', 'ge'), ('nl', 'ge'), ('le', 'le'), ('ng', 'le'), ('g', 'g'), ('nle', 'g')]

out = []
p = out.append


def tokens(s):
    """Splits at spaces outside of string literals and parentheses."""
    toks, cur, depth, q = [], '', 0, False
    for ch in s:
        if ch == '"':
            q = not q
        elif not q and ch in '(⸨':
            depth += 1
        elif not q and ch in ')⸩':
            depth -= 1
        if ch == ' ' and not q and depth == 0:
            if cur:
                toks.append(cur)
            cur = ''
        else:
            cur += ch
    if cur:
        toks.append(cur)
    return toks


def align(rows):
    """`rows` are lists of fields; each field is a string, split into tokens. Pads the tokens so
    that equal positions line up, as long as the rows of a field have the same number of tokens."""
    nf = len(rows[0])
    cols = []
    for f in range(nf):
        ts = [tokens(r[f]) for r in rows]
        if len({len(t) for t in ts}) == 1:
            widths = [max(len(t[i]) for t in ts) for i in range(len(ts[0]))]
            cols.append([' '.join(t[i].ljust(widths[i]) for i in range(len(t))) for t in ts])
        else:
            cols.append([r[f] for r in rows])
    w = [max(len(c[i]) for c in cols) for i in range(len(rows))] if False else None
    fw = [max(len(cols[f][i]) for i in range(len(rows))) for f in range(nf)]
    return [' '.join(cols[f][i].ljust(fw[f]) for f in range(nf)).rstrip() for i in range(len(rows))]


def group(rules, title=None):
    """Emits a group of rules `(opts, items, cat, rhs)`, aligned."""
    if title:
        p(f'-- {title}')
    rows = [['notation', opts, items, 'in', cat, '=>', rhs] for opts, items, cat, rhs in rules]
    for line in align(rows):
        p(re.sub(r'notation +', 'notation ', line, count=1) if not any(r[1] for r in rows) else line)
    p('')


def opt(print_=True, prio=None):
    s = ''
    if prio:
        s += f'(priority := {prio})'
    if not print_:
        s += (' ' if s else '') + '(print := false)'
    return s


p('''module

public import Kraken.X64.Parser.Elab
public meta import Kraken.X64.Parser.Elab

/-!
The `notation ... in c` rules of the X64 syntax, generated by `gen_rules.py` (in this directory).
See `design.md` for the design: one category per operation width (issue 8), one rule per mnemonic
spelling (issue 3), and parse-only unsuffixed spellings (issue 2). 32-bit addresses are written
with a `.byte 0x67;` prefix (issue 1); the parse-only rules for 32-bit register names in
addresses are not included yet.
-/

public meta section
''')

# ---------------------------------------------------------------- categories and embeddings
p('-- Categories, embeddings and escapes')
for n, s in W:
    p(f'declare_syntax_cat x64_register{n}')
for n, x in AVX:
    p(f'declare_syntax_cat x64_avx_register{n}')
for n, s in W:
    p(f'declare_syntax_cat x64_rm{n}')
    p(f'declare_syntax_cat x64_operand{n}')
for n, x in AVX:
    p(f'declare_syntax_cat x64_avx_rm{n}')
for n, s in W:
    p(f'declare_syntax_cat x64_operation{n} (behavior := both)')
for n, x in AVX:
    p(f'declare_syntax_cat x64_avx_operation{n} (behavior := both)')
p('declare_syntax_cat x64_instruction (behavior := both)')
p('declare_syntax_cat x64_directive (behavior := both)')
p('')
entries = [('⸨reg| ', f'x64_register{n}') for n, _ in W] + \
          [('⸨reg| ', f'x64_avx_register{n}') for n, _ in AVX] + \
          [('⸨base| ', 'x64_base'), ('⸨index| ', 'x64_index'), ('⸨mem| ', 'x64_memory')] + \
          [('⸨rm| ', f'x64_rm{n}') for n, _ in W] + [('⸨rm| ', f'x64_avx_rm{n}') for n, _ in AVX] + \
          [('⸨operand| ', f'x64_operand{n}') for n, _ in W] + \
          [('⸨shift| ', 'x64_shift_count'), ('⸨target| ', 'x64_jump_target')] + \
          [('⸨operation| ', f'x64_operation{n}') for n, _ in W] + \
          [('⸨operation| ', f'x64_avx_operation{n}') for n, _ in AVX] + \
          [('⸨instr| ', 'x64_instruction'), ('⸨dir| ', 'x64_directive')]
rows = [['entry_notation', f'"{e}"', f'x:{c}', '" ⸩"', '=>', 'x'] for e, c in entries]
for line in align(rows):
    p(line)
p('')
escapes = [('"%" noWs "❰"', f'x64_register{n}') for n, _ in W] + \
          [('"%" noWs "❰"', f'x64_avx_register{n}') for n, _ in AVX] + [('"%" noWs "❰"', 'x64_base')] + \
          [('"❰"', f'x64_rm{n}') for n, _ in W] + [('"❰"', f'x64_avx_rm{n}') for n, _ in AVX] + \
          [('"❰"', f'x64_operand{n}') for n, _ in W] + \
          [('"❰"', 'x64_jump_target'), ('"❰"', 'x64_instruction'), ('"❰"', 'x64_directive')]
rows = [['escape_notation', o, 'e:term', '"❱"', 'in', c, '=>', 'e'] for o, c in escapes]
for line in align(rows):
    p(line)
p('')

# ---------------------------------------------------------------- registers
group([('', f'"%" noWs &"{r}"', 'x64_base', f'Reg64.{r}') for r in REG64],
      'Address registers (`Reg64`). Register rules use their printed form, `⸨base| %rax ⸩` (issue 5).')
for r in REG64:
    group([('', f'"%" noWs &"{reg_name(r, n)}"', f'x64_register{n}', f'Reg.low ⸨base| %{r} ⸩ Width.W{n}')
           for n, _ in reversed(W)])
group([('', f'"%" noWs &"{h}"', 'x64_register8', f'Reg.{h}') for h in ['ah', 'bh', 'ch', 'dh']])
for i in range(32):
    group([('', f'"%" noWs &"{x}{i}"', f'x64_avx_register{n}', f'AvxReg.{x} RegMm.mm{i}') for n, x in AVX])

# ---------------------------------------------------------------- memory and operands
group([('', '", " i:x64_base', 'x64_index', 'AddrIndex.mk i Width.W8'),
       (opt(False), '", " i:x64_base ", " 1', 'x64_index', 'AddrIndex.mk i Width.W8')] +
      [('', f'", " i:x64_base ", " {k}', 'x64_index', f'AddrIndex.mk i Width.W{w}') for k, w in [(2, 16), (4, 32), (8, 64)]],
      'Index and scale')
group([('', 'd:x64_const', 'x64_memory', 'AddrExpr.mk none none d'),
       ('', 'd:x64_const "(" b:x64_base ")"', 'x64_memory', 'AddrExpr.mk (some (RegOrRip.reg b)) none d'),
       ('', 'd:x64_const "(" b:x64_base i:x64_index ")"', 'x64_memory', 'AddrExpr.mk (some (RegOrRip.reg b)) (some i) d'),
       ('', '"(" b:x64_base ")"', 'x64_memory', 'AddrExpr.mk (some (RegOrRip.reg b)) none ⸨const| 0 ⸩'),
       ('', '"(" b:x64_base i:x64_index ")"', 'x64_memory', 'AddrExpr.mk (some (RegOrRip.reg b)) (some i) ⸨const| 0 ⸩')],
      'Memory operands (`disp(%rip)` is in `Syntax.lean`)')
group([('', f'r:x64_register{n}', f'x64_rm{n}', f'@RegOrMem.reg Width.W{n} r') for n, _ in W] +
      [('', 'm:x64_memory', f'x64_rm{n}', f'@RegOrMem.mem Width.W{n} m') for n, _ in W],
      'Register or memory')
group([('(priority := low)', f'x:x64_rm{n}', f'x64_operand{n}', f'@Operand.regOrMem Width.W{n} x') for n, _ in W] +
      [('', f'"$" c:x64_const', f'x64_operand{n}', f'@Operand.imm Width.W{n} c') for n, _ in W],
      'Operands. `$sym` is read as an antiquotation (issue 6, TODO).')
group([('', f'r:x64_avx_register{n}', f'x64_avx_rm{n}', f'@AvxRegOrMem.avx AvxWidth.W{n} r') for n, _ in AVX] +
      [('', 'm:x64_memory', f'x64_avx_rm{n}', f'@AvxRegOrMem.mem AvxWidth.W{n} m') for n, _ in AVX])
group([('', '"%" noWs &"cl"', 'x64_shift_count', 'ShiftCountExpr.cl'),
       ('', '"$" c:x64_const', 'x64_shift_count', 'ShiftCountExpr.imm8 c')], 'Shift counts')
group([('', 'r:x64_register64', 'x64_jump_target', 'RelRegOrMem.reg r'),
       ('(priority := low)', 'm:x64_memory', 'x64_jump_target', 'RelRegOrMem.mem m')],
      'Jump targets (a label, relative to the next instruction, is in `Syntax.lean`)')

# ---------------------------------------------------------------- operations
groups = {}   # stem -> list of rules
order = []


def form(stem, n, m, vars_, rhs, print_=True, avx=False):
    if stem not in groups:
        groups[stem] = []
        order.append(stem)
    cat = f'x64_avx_operation{n}' if avx else f'x64_operation{n}'
    if vars_:
        parts = [f'&"{m} "']
        for i, (v, k) in enumerate(vars_):
            if i:
                parts.append('", "')
            parts.append('lineEq')
            parts.append(f'"$" {v}:x64_const' if k == 'I' else f'{v}:{cat_of(k, n)}')
        items = ' '.join(parts)
    else:
        # Mnemonics are non-reserved keywords, so that they stay usable as Lean identifiers.
        items = ' '.join([f'&"{t} "' for t in m.split()[:-1]] + [f'&"{m.split()[-1]}"'])
    groups[stem].append((opt(print_), items, cat, rhs))


def cat_of(kind, n):
    if kind == 'O': return f'x64_operand{n}'
    if kind == 'R': return f'x64_rm{n}'
    if kind == 'G': return f'x64_register{n}'
    if kind == 'M': return 'x64_memory'
    if kind == 'S': return 'x64_shift_count'
    if kind == 'T': return 'x64_jump_target'
    if kind == 'L': return 'x64_ident'
    if kind == 'N': return 'num'
    if kind[0] == 'R': return f'x64_rm{kind[1:]}'
    if kind[0] == 'G': return f'x64_register{kind[1:]}'
    if kind[0] == 'A': return f'x64_avx_rm{kind[1:]}'
    if kind[0] == 'V': return f'x64_avx_register{kind[1:]}'
    raise ValueError(kind)


BIN = [('add', 'add'), ('adc', 'adc'), ('sub', 'sub'), ('sbb', 'sbb'), ('mov', 'mov'),
       ('movabs', 'mov'), ('xor', 'xor'), ('and', 'and'), ('or', 'or'), ('cmp', 'cmp'),
       ('test', 'test')]
UN = ['mul', 'neg', 'dec', 'inc', 'not']
SH = [('shl', 'shl'), ('sal', 'shl'), ('shr', 'shr'), ('sar', 'sar'), ('rol', 'rol'),
      ('ror', 'ror'), ('rcl', 'rcl'), ('rcr', 'rcr')]
EXT = [('bw', 8, 16), ('bl', 8, 32), ('bq', 8, 64), ('wl', 16, 32), ('wq', 16, 64)]
W64 = 'Width.W64'


def widths(stem_widths, fn):
    """`fn(n, s, spell, printed)` for each width, suffixed (printed) first, then unsuffixed."""
    for spell_suffixed in [True, False]:
        for n, s in W:
            if n in stem_widths:
                fn(n, s if spell_suffixed else '', spell_suffixed)


ALL = [8, 16, 32, 64]
for m, c in BIN:
    widths(ALL, lambda n, s, pr: form(m, n, m + s, [('s', 'O'), ('d', 'R')], f'@Operation.{c} Width.W{n} d s', pr and m != 'movabs'))
for m in ['adcx', 'adox']:
    widths([32, 64], lambda n, s, pr: form(m, n, m + s, [('s', 'R'), ('d', 'G')], f'@Operation.{m} Width.W{n} d s', pr))
widths([32, 64], lambda n, s, pr: form('mulx', n, 'mulx' + s, [('s', 'R'), ('lo', 'G'), ('hi', 'G')], f'@Operation.mulx Width.W{n} hi lo s', pr))
for m in UN:
    widths(ALL, lambda n, s, pr: form(m, n, m + s, [('d', 'R')], f'@Operation.{m} Width.W{n} d', pr))
widths(ALL, lambda n, s, pr: form('imul', n, 'imul' + s, [('s', 'R')], f'@Operation.imul1 Width.W{n} s', pr))
widths(ALL, lambda n, s, pr: form('imul', n, 'imul' + s, [('s', 'O'), ('d', 'R')], f'@Operation.imul Width.W{n} none d s', pr))
widths(ALL, lambda n, s, pr: form('imul', n, 'imul' + s, [('s1', 'O'), ('s2', 'R'), ('d', 'R')], f'@Operation.imul Width.W{n} (some d) s2 s1', pr))
widths(ALL, lambda n, s, pr: form('lea', n, 'lea' + s, [('m', 'M'), ('d', 'G')], f'@Operation.lea Width.W{n} d m', pr))
for m, c in SH:
    widths(ALL, lambda n, s, pr: form(c, n, m + s, [('c', 'S'), ('d', 'R')], f'@Operation.{c} Width.W{n} d c', pr and m != 'sal'))
    widths(ALL, lambda n, s, pr: form(c, n, m + s, [('d', 'R')], f'@Operation.{c} Width.W{n} d ⸨shift| $1 ⸩', False))
for m in ['shld', 'shrd']:
    widths([16, 32, 64], lambda n, s, pr: form(m, n, m + s, [('c', 'S'), ('s', 'G'), ('d', 'R')], f'@Operation.{m} Width.W{n} d s c', pr))
widths([32, 64], lambda n, s, pr: form('bswap', n, 'bswap' + s, [('d', 'G')], f'@Operation.bswap Width.W{n} d', pr))
# push and pop: unsuffixed, the width of a register, else 64 bits
for m, kind, rhs in [('push', 'O', 's'), ('pop', 'R', 'd')]:
    v = rhs
    for n, s in W:
        form(m, n, m + s, [(v, kind)], f'@Operation.{m} Width.W{n} {v}')
    for n, s in W:
        if n == 64:
            form(m, n, m, [(v, kind)], f'@Operation.{m} Width.W64 {v}', False)
        else:
            inner = f'(@Operand.regOrMem Width.W{n} (@RegOrMem.reg Width.W{n} r))' if m == 'push' else f'(@RegOrMem.reg Width.W{n} r)'
            form(m, n, m, [('r', 'G')], f'@Operation.{m} Width.W{n} {inner}', False)
for n, s in W:
    for spell, c in CC:
        form('cmov', n, 'cmov' + spell, [('s', 'R'), ('d', 'G')], f'@Operation.cmovcc Width.W{n} CondCode.{c} d s', spell == c)
for spell, c in CC:
    form('set', 8, 'set' + spell, [('d', 'R')], f'@Operation.setcc Width.W8 CondCode.{c} d', spell == c)
for sfx, a, b in EXT + [('lq', 32, 64), ('xd', 32, 64)]:
    form('movsx', b, 'movs' + sfx, [('s', f'R{a}'), ('d', 'R')], f'@Operation.movsx Width.W{b} Width.W{a} d s', sfx != 'xd')
for a, _ in W:
    for b, _ in W:
        if a < b:
            form('movsx', b, 'movsx', [('s', f'G{a}'), ('d', 'G')],
                 f'@Operation.movsx Width.W{b} Width.W{a} (@RegOrMem.reg Width.W{b} d) (@RegOrMem.reg Width.W{a} s)', False)
for sfx, a, b in EXT:
    form('movzx', b, 'movz' + sfx, [('s', f'R{a}'), ('d', 'R')], f'@Operation.movzx Width.W{b} Width.W{a} d s')
for a, _ in W:
    for b, _ in W:
        if a < b:
            form('movzx', b, 'movzx', [('s', f'G{a}'), ('d', 'G')],
                 f'@Operation.movzx Width.W{b} Width.W{a} (@RegOrMem.reg Width.W{b} d) (@RegOrMem.reg Width.W{a} s)', False)
for m in ['movs', 'stos']:
    for n, s in W:
        form(m, n, m + s, [], f'@Operation.{m} Width.W{n} false')
    for n, s in W:
        form(m, n, f'rep {m}{s}', [], f'@Operation.{m} Width.W{n} true')
for spell, c in CC:
    form('j', 64, 'j' + spell, [('l', 'L')], f'@Operation.jcc {W64} CondCode.{c} l', spell == c)
for m in ['call', 'jmp']:
    form(m, 64, m, [('t', 'T')], f'@Operation.{m} {W64} t')
    form(m, 64, m + 'q', [('t', 'T')], f'@Operation.{m} {W64} t', False)
for m, pr in [('ret', True), ('retq', False)]:
    form('ret', 64, m, [], f'@Operation.ret {W64}', pr)
for m in ['cld', 'std']:
    form(m, 64, m, [], f'@Operation.{m} {W64}')
form('nop', 64, 'nop', [], f'@Operation.nop {W64} 1')
form('nop', 64, 'nop', [('k', 'N')], f'@Operation.nop {W64} k')

# AVX
AVX2 = ['movups', 'vmovups', 'movaps', 'addps', 'subps', 'movdqu', 'vmovdqu', 'movdqa', 'paddd', 'pshufb']
for m in AVX2:
    for n, x in AVX:
        form(m, n, m, [('s', f'A{n}'), ('d', f'A{n}')], f'@AvxOperation.{m} AvxWidth.W{n} d s', avx=True)
for m in ['pshufd', 'palignr', 'pblendw']:
    for n, x in AVX:
        form(m, n, m, [('i', 'I'), ('s', f'A{n}'), ('d', f'A{n}')], f'@AvxOperation.{m} AvxWidth.W{n} d s i', avx=True)
form('vmov', 128, 'vmovq', [('s', 'V128'), ('d', 'V128')], '@AvxOperation.vmovq AvxWidth.W128 d s', avx=True)
for m, k in [('vmovd', 32), ('vmovq', 64)]:
    form('vmov', 128, m, [('s', 'V128'), ('d', f'R{k}')], f'@AvxOperation.vmovOut AvxWidth.W128 Width.W{k} d s', avx=True)
    form('vmov', 128, m, [('s', f'R{k}'), ('d', 'V128')], f'@AvxOperation.vmovIn AvxWidth.W128 Width.W{k} d s', avx=True)
form('vzeroupper', 128, 'vzeroupper', [], '@AvxOperation.vzeroupper AvxWidth.W128', avx=True)

p('-- ============================================================================')
p('-- Operations, one group per mnemonic stem')
p('-- ============================================================================')
p('')
for stem in order:
    group(groups[stem])

# ---------------------------------------------------------------- instructions and directives
p('-- Instructions. All wrappers of the operation categories have the same priority (issue 2).')
rows = []
for n, _ in W:
    rows.append(('(priority := high)', f'o:x64_operation{n}', 'x64_instruction', f'Instr.regular Width.W64 Width.W{n} o'))
    rows.append(('', f'"." noWs &"byte " 0x67 "; " o:x64_operation{n}', 'x64_instruction', f'Instr.regular Width.W32 Width.W{n} o'))
for n, _ in AVX:
    rows.append(('(priority := high)', f'o:x64_avx_operation{n}', 'x64_instruction', f'Instr.avx Width.W64 AvxWidth.W{n} o'))
    rows.append(('', f'"." noWs &"byte " 0x67 "; " o:x64_avx_operation{n}', 'x64_instruction', f'Instr.avx Width.W32 AvxWidth.W{n} o'))
group(rows)
group([('', '"." noWs &"align " lineEq a:num', 'x64_instruction', 'Instr.regular Width.W64 Width.W64 (@Operation.nopalign Width.W64 a none)'),
       ('', '"." noWs &"align " lineEq a:num ", " lineEq b:num', 'x64_instruction', 'Instr.regular Width.W64 Width.W64 (@Operation.nopalign Width.W64 a (some b))')])
group([('(priority := low)', 'i:x64_instruction', 'x64_directive', 'Kraken.Directive.instr i'),
       ('', 'l:x64_ident lineEq ":"', 'x64_directive', 'Kraken.Directive.label l')] +
      [('', f'"." noWs &"{w} " lineEq c:x64_const', 'x64_directive', f'Kraken.Directive.word {b} c') for w, b in [('short', 2), ('long', 4), ('quad', 8)]],
      'Directives')
p('end')

sys.stdout.write('\n'.join(out) + '\n')
